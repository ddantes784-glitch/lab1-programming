# считываем целое число
n = int(input("Введите число: "))
# отдельно обрабатываем случай нуля — его двоичная запись "0"
if n == 0:
    # присваиваем результату строку "0"
    result = "0"
# иначе запускаем алгоритм деления на 2
else:
    # создаём пустой список для остатков
    digits = []
    # цикл выполняется, пока число больше нуля
    while n > 0:
        # остаток от деления на 2 добавляем в список
        digits.append(str(n % 2))
        # целочисленно делим число на 2
        n //= 2
    # остатки шли в обратном порядке — разворачиваем и склеиваем в строку
    result = "".join(reversed(digits))
# выводим результат
print(result)